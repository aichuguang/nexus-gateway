// generation excludes persistence bookkeeping and unused certificate slots so
// applying a revision or importing an unrelated certificate cannot change it.
// It covers every resource that can alter the rendered proxy configuration.
//
// publicAddress is part of the hash because it is written into the listen
// directives. Leaving it out would let a changed address produce an identical
// generation, and the activation check would then confirm a configuration that
// is no longer the one being served.
func generation(state model.State, publicAddress string) string {
	input := struct {
		Revision      int64
		GatewayIP     string
		PublicAddress string
		Services      []generationService
	}{Revision: state.Revision, GatewayIP: state.Settings.GatewayIP, PublicAddress: publicAddress, Services: []generationService{}}
	fingerprints := serviceFingerprints(state)
	for _, s := range state.Services {
		input.Services = append(input.Services, generationServiceOf(s, fingerprints))
	}
	sort.Slice(input.Services, func(i, j int) bool { return input.Services[i].ID < input.Services[j].ID })
	encoded, _ := json.Marshal(input)
	sum := sha256.Sum256(encoded)
	return hex.EncodeToString(sum[:])
}

// generationService is the part of a service the hash covers: exactly the fields
// that change what the proxy serves for it. Keeping the definition in one place
// is what lets ServiceGeneration below answer "has this row changed?" without a
// second notion of "changed" that could drift away from this one.
type generationService struct {
	ID, Upstream string
	Domains      []string
	Certificate  string
	Fingerprint  string
	Port         int
	Enabled      bool
}

func serviceFingerprints(state model.State) map[string]string {
	fingerprints := make(map[string]string, len(state.Certificates))
	for _, cert := range state.Certificates {
		fingerprints[cert.ID] = cert.Fingerprint
		if cert.MaterialVersion != "" {
			fingerprints[cert.ID] += "/" + cert.MaterialVersion
		}
	}
	return fingerprints
}

func generationServiceOf(s model.Service, fingerprints map[string]string) generationService {
	domains := append([]string{}, s.Domains...)
	for i := range domains {
		domains[i] = strings.ToLower(domains[i])
	}
	sort.Strings(domains)
	item := generationService{ID: s.ID, Upstream: s.Upstream, Domains: domains, Certificate: s.CertificateID, Port: s.PublishedPort(), Enabled: s.Enabled}
	if s.Enabled && s.UsesDomains() {
		item.Fingerprint = fingerprints[s.CertificateID]
	}
	return item
}

// ServiceGeneration is one service's contribution to the generation hash. The
// dashboard asks it whether a row still has changes that are not running, and
// the answer has to come from the same fields as the hash: a tag driven by any
// other notion of "changed" would light up for edits that alter nothing served,
// and an operator who learns to ignore tags stops applying real ones.
func ServiceGeneration(state model.State, s model.Service) string {
	encoded, _ := json.Marshal(generationServiceOf(s, serviceFingerprints(state)))
	sum := sha256.Sum256(encoded)
	return hex.EncodeToString(sum[:])
}

// VerifyApplied checks a loopback-only response generated by the active nginx
// workers, rather than assuming that an asynchronous reload signal succeeded.
func (e *Engine) VerifyApplied(state model.State, publicAddress string) error {
	if e.DryRun {
		return nil
	}
	return e.probeGeneration(generation(state, publicAddress))
}

func (e *Engine) probeGeneration(expected string) error {
	if e.generationProbe != nil {
		return e.generationProbe(expected)
	}
	return verifyGeneration("http://127.0.0.1:18079/__gateway_generation", expected)
}

// Nginx reload only queues a signal. A small bounded retry allows worker startup
// without reporting a failed asynchronous activation as a successful apply.
func (e *Engine) waitGeneration(expected string) error {
	var err error
	for attempt := 0; attempt < 4; attempt++ {
		if attempt > 0 {
			time.Sleep(150 * time.Millisecond)
		}
		if err = e.probeGeneration(expected); err == nil {
			return nil
		}
	}
	return err
}

// The rendered probe body carries a literal backslash-n: nginx does not
// unescape it, so the expression escapes the backslash instead of asking for
// a newline. Matching a newline never matched, which silently skipped the
// rollback generation check below.
var renderedGeneration = regexp.MustCompile(`return 200 "([a-f0-9]{64})\\n";`)

func verifyGeneration(endpoint, expected string) error {
	return verifyGenerationContext(context.Background(), endpoint, expected)
}

func verifyGenerationContext(ctx context.Context, endpoint, expected string) error {
	ctx, cancel := context.WithTimeout(ctx, 2*time.Second)
	defer cancel()
	transport := &http.Transport{
		Proxy: nil, DisableKeepAlives: true,
		DialContext:           (&net.Dialer{Timeout: time.Second}).DialContext,
		ResponseHeaderTimeout: time.Second,
	}
	defer transport.CloseIdleConnections()
	client := &http.Client{Transport: transport, Timeout: 2 * time.Second, CheckRedirect: func(_ *http.Request, _ []*http.Request) error { return http.ErrUseLastResponse }}
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, endpoint, nil)
	if err != nil {
		return fmt.Errorf("无法构造受管代际探测请求")
	}
	resp, err := client.Do(req)
	if err != nil {
		return fmt.Errorf("受管 nginx 的代际探测端点不可达")
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("受管 nginx 的代际探测端点返回了意外状态码")
	}
	body, err := io.ReadAll(io.LimitReader(resp.Body, 128))
	if err != nil || string(body) != expected+"\n" {
		return fmt.Errorf("受管 nginx 尚未生效预期的配置代际")
	}
	return nil
}
